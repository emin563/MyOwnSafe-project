#!/usr/bin/env node
/**
 * After: eas credentials → Download credentials from EAS to credentials.json
 * Run: npm run android:sync-credentials
 *
 * Writes android/keystore.properties with paths relative to android/ so Gradle can sign
 * release AABs with the same key as EAS (upload key).
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const credPath = path.join(root, 'credentials.json');
const androidDir = path.join(root, 'android');
const outProps = path.join(androidDir, 'keystore.properties');

if (!fs.existsSync(credPath)) {
  console.error(
    'Missing credentials.json. Run: eas credentials → Android → production →\n' +
      '  "credentials.json: Upload/Download..." → "Download credentials from EAS to credentials.json"\n' +
      'Run this from the project root: ' +
      root
  );
  process.exit(1);
}

let raw;
try {
  raw = JSON.parse(fs.readFileSync(credPath, 'utf8'));
} catch (e) {
  console.error('Could not parse credentials.json:', e.message);
  process.exit(1);
}

const k = raw.android?.keystore;
if (!k) {
  console.error('credentials.json has no android.keystore. Expected shape:\n' + '  { "android": { "keystore": { "keystorePath", "keystorePassword", "keyAlias", "keyPassword" } } }');
  process.exit(1);
}

const keystorePath = k.keystorePath || k.keystore;
if (!keystorePath) {
  console.error('android.keystore is missing keystorePath');
  process.exit(1);
}

const absKeystore = path.isAbsolute(keystorePath) ? keystorePath : path.join(root, keystorePath);
if (!fs.existsSync(absKeystore)) {
  console.error('Keystore file not found at:', absKeystore);
  console.error('(from keystorePath in credentials.json:', keystorePath + ')');
  process.exit(1);
}

// Gradle rootProject.file() is relative to the `android` project directory
const relFromAndroid = path.relative(androidDir, absKeystore);
if (relFromAndroid.startsWith('..')) {
  // ok: ../credentials/foo.jks
} else {
  // same folder or under android/
}

const storeFile = relFromAndroid.split(path.sep).join('/');

const keyAlias = k.keyAlias;
const storePassword = k.keystorePassword;
const keyPassword = k.keyPassword != null && k.keyPassword !== '' ? k.keyPassword : k.keystorePassword;

if (!keyAlias || !storePassword) {
  console.error('android.keystore must include keyAlias and keystorePassword');
  process.exit(1);
}

const lines = [
  '# Generated by npm run android:sync-credentials from credentials.json — do not commit (see .gitignore)',
  `# SHA1 should match Play upload key: keytool -list -v -keystore "<path>" -alias ${keyAlias}`,
  `storeFile=${storeFile}`,
  `keyAlias=${keyAlias}`,
  `storePassword=${storePassword}`,
  `keyPassword=${keyPassword}`,
  '',
];

fs.writeFileSync(outProps, lines.join('\n'), 'utf8');
console.log('Wrote', outProps);
console.log('storeFile (from android/):', storeFile);
console.log('keyAlias:', keyAlias);
console.log('Next: npm run build:android:aab');
